import { describe, it, expect, beforeEach, afterEach } from "vitest";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import {
  GENERATED_INSTRUCTIONS_FILE,
  composeInstructions,
  parseSections,
} from "./instructions.js";
import type { RenderPlan, ResolvedLoadout } from "./types.js";

let tmpDir: string;
let projectRoot: string;
let loadoutRoot: string;

beforeEach(() => {
  tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "loadout-instructions-test-"));
  projectRoot = path.join(tmpDir, "project");
  loadoutRoot = path.join(projectRoot, ".loadouts");
  fs.mkdirSync(path.join(loadoutRoot, "instructions"), { recursive: true });
});

afterEach(() => {
  fs.rmSync(tmpDir, { recursive: true, force: true });
});

function source(name: string, content: string): string {
  const p = path.join(loadoutRoot, "instructions", name);
  fs.writeFileSync(p, content);
  return p;
}

function planFor(name: string, sourcePaths: string[], tools = ["opencode"]) {
  const loadout = { name } as ResolvedLoadout;
  const plan: RenderPlan = {
    outputs: sourcePaths.flatMap((sourcePath) =>
      tools.map((tool) => ({
        spec: { tool, kind: "instruction", sourcePath, targetPath: "AGENTS.md", mode: "symlink" as const },
        item: { kind: "instruction", sourcePath, relativePath: path.basename(sourcePath), tools },
        hash: "",
      }))
    ),
    shadowed: [],
    errors: [],
  };
  return { loadout, plan };
}

const opts = () => ({ loadoutRoot, projectRoot, scope: "project" as const });

describe("composeInstructions", () => {
  it("returns null with no instruction outputs", () => {
    expect(composeInstructions([planFor("base", [])], opts())).toBeNull();
  });

  it("produces the golden content for one source", () => {
    const base = source("AGENTS.base.md", "# Base\n\nBe nice.\n\n\n");
    const composition = composeInstructions([planFor("base", [base])], opts())!;

    expect(composition.generatedPath).toBe(path.join(loadoutRoot, GENERATED_INSTRUCTIONS_FILE));
    expect(composition.content).toBe(
      [
        "<!--",
        "  Generated by loadouts. Do not edit this file.",
        "  `loadouts sync` will not overwrite local edits here; it reports them instead.",
        "  Edit the source named in each section, then run `loadouts sync`:",
        "    - .loadouts/instructions/AGENTS.base.md (loadout: base)",
        "-->",
        "",
        "<!-- loadouts:begin base · .loadouts/instructions/AGENTS.base.md -->",
        "# Base",
        "",
        "Be nice.",
        "<!-- loadouts:end base · .loadouts/instructions/AGENTS.base.md -->",
        "",
      ].join("\n")
    );
    expect(composition.destinations).toEqual([{ targetPath: "AGENTS.md", tools: ["opencode"] }]);
  });

  it("produces the golden content for two sources in plan order", () => {
    const base = source("AGENTS.base.md", "# Base\n");
    const py = source("AGENTS.py.md", "---\ntitle: py\n---\n# Python\n");
    const composition = composeInstructions(
      [planFor("base", [base], ["cursor", "codex"]), planFor("py", [py], ["opencode"])],
      opts()
    )!;

    expect(composition.content).toBe(
      [
        "<!--",
        "  Generated by loadouts. Do not edit this file.",
        "  `loadouts sync` will not overwrite local edits here; it reports them instead.",
        "  Edit the source named in each section, then run `loadouts sync`:",
        "    - .loadouts/instructions/AGENTS.base.md (loadout: base)",
        "    - .loadouts/instructions/AGENTS.py.md (loadout: py)",
        "-->",
        "",
        "<!-- loadouts:begin base · .loadouts/instructions/AGENTS.base.md -->",
        "# Base",
        "<!-- loadouts:end base · .loadouts/instructions/AGENTS.base.md -->",
        "",
        "<!-- loadouts:begin py · .loadouts/instructions/AGENTS.py.md -->",
        "---",
        "title: py",
        "---",
        "# Python",
        "<!-- loadouts:end py · .loadouts/instructions/AGENTS.py.md -->",
        "",
      ].join("\n")
    );
    expect(composition.destinations).toEqual([
      { targetPath: "AGENTS.md", tools: ["codex", "cursor", "opencode"] },
    ]);
  });

  it("dedupes the same file across loadouts, keeping the first loadout name", () => {
    const shared = source("AGENTS.shared.md", "# Shared\n");
    const py = source("AGENTS.py.md", "# Python\n");
    const composition = composeInstructions(
      [planFor("base", [shared]), planFor("py", [shared, py])],
      opts()
    )!;

    expect(composition.sources.map((s) => [s.loadout, path.basename(s.sourcePath)])).toEqual([
      ["base", "AGENTS.shared.md"],
      ["py", "AGENTS.py.md"],
    ]);
    expect(composition.content.match(/loadouts:begin/g)).toHaveLength(2);
  });
});

describe("parseSections", () => {
  it("round-trips composed content", () => {
    const base = source("AGENTS.base.md", "# Base\n");
    const py = source("AGENTS.py.md", "# Python\n\nline\n");
    const composition = composeInstructions([planFor("base", [base]), planFor("py", [py])], opts())!;

    expect(parseSections(composition.content)).toEqual(
      composition.sources.map((s) => ({ loadout: s.loadout, displayPath: s.displayPath, body: s.body }))
    );
  });

  it("returns null when an end marker is missing", () => {
    const base = source("AGENTS.base.md", "# Base\n");
    const py = source("AGENTS.py.md", "# Python\n");
    const composition = composeInstructions([planFor("base", [base]), planFor("py", [py])], opts())!;
    const damaged = composition.content.replace(
      "<!-- loadouts:end py · .loadouts/instructions/AGENTS.py.md -->",
      ""
    );

    expect(parseSections(damaged)).toBeNull();
  });

  it("returns null when there are no sections", () => {
    expect(parseSections("# Hand-written\n")).toBeNull();
  });
});
